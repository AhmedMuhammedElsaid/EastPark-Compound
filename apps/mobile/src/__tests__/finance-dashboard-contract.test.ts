import { readFileSync } from "node:fs";
import { join } from "node:path";

import { makeDashboard } from "./fixtures/finance-dashboard";
import contract from "./fixtures/finance-dashboard.contract.json";

/** Every `path: type` leaf; arrays are walked element by element so no row can drift unnoticed. */
function shape(value: unknown, path = "$"): string[] {
  if (value === null)
    return [`${path}: null`];
  if (Array.isArray(value))
    return value.length > 0 ? value.flatMap(item => shape(item, `${path}[]`)) : [`${path}: array`];
  if (typeof value === "object")
    return Object.entries(value as Record<string, unknown>).flatMap(([key, child]) => shape(child, `${path}.${key}`));
  return [`${path}: ${typeof value}`];
}

/** Types seen at each path; `null` and `array` (an empty list) are not concrete types. */
function typesByPath(value: unknown): Map<string, Set<string>> {
  const out = new Map<string, Set<string>>();
  for (const line of new Set(shape(value))) {
    const [path, type] = line.split(": ");
    out.set(path, (out.get(path) ?? new Set()).add(type));
  }
  return out;
}

const concrete = (types: Set<string>) => [...types].filter(t => t !== "null" && t !== "array").sort();
/** Paths with a concrete value somewhere; a list that is empty in one sample only has its `array` marker. */
const paths = (map: Map<string, Set<string>>) => [...map].filter(([, types]) => concrete(types).length > 0 || types.has("null")).map(([path]) => path).sort();

describe("backend dashboard contract fixture (generated by the backend dashboard spec)", () => {
  it("has the key paths and value types of the mobile test fixture", () => {
    const real = typesByPath(contract);
    const mobile = typesByPath(makeDashboard());
    expect(paths(real)).toEqual(paths(mobile));
    for (const [path, types] of real) {
      const a = concrete(types);
      const b = concrete(mobile.get(path) ?? new Set());
      if (a.length > 0 && b.length > 0)
        expect(a).toEqual(b);
    }
  });

  it("sends money as decimal strings and counts as numbers", () => {
    const money = /^-?\d+\.\d{2}$/;
    expect(contract.outstanding).toMatch(money);
    expect(contract.aging.over90).toMatch(money);
    expect(contract.collected.every(m => money.test(m.amount))).toBe(true);
    expect(contract.byBuilding.every(b => money.test(b.outstanding) && typeof b.totalFlats === "number")).toBe(true);
    expect(typeof contract.owingFlats).toBe("number");
    expect(typeof contract.unapplied.count).toBe("number");
    expect(contract.cohort.rate === null || typeof contract.cohort.rate === "string").toBe(true);
    expect(contract.period.status === "OPEN" || contract.period.status === "CLOSED").toBe(true);
  });

  it("is byte-identical in the backend, web and mobile copies", () => {
    const apps = join(__dirname, "../../..");
    const read = (path: string) => readFileSync(join(apps, path));
    const backend = read("backend/test/fixtures/finance-dashboard.contract.json");
    expect(read("web/src/test/fixtures/finance-dashboard.contract.json").equals(backend)).toBe(true);
    expect(read("mobile/src/__tests__/fixtures/finance-dashboard.contract.json").equals(backend)).toBe(true);
  });
});
