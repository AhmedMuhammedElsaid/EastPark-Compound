import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import * as React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { describe, expect, it, vi } from 'vitest';

import { FinanceDashboardView } from '@/components/finance/FinanceDashboard';
import { dashboardSchema, type Dashboard } from '@/lib/finance/dashboard';
import { LanguageProvider } from '@/lib/i18n/LanguageProvider';
import ar from '@/translations/ar.json';

vi.mock('next/link', () => ({
  default: ({ href, children, ...rest }: { href: string; children: React.ReactNode }) => React.createElement('a', { href, ...rest }, children),
}));

const h = React.createElement;
const raw = JSON.parse(readFileSync(fileURLToPath(new URL('./fixtures/finance-dashboard.contract.json', import.meta.url)), 'utf8')) as unknown;

function view(data: Dashboard | null, error = '') {
  return renderToStaticMarkup(h(LanguageProvider, null, h(FinanceDashboardView, { data, error, onRetry: () => {} })));
}

describe('backend contract fixture (generated by the backend dashboard spec)', () => {
  it('parses with the strict web schema and loses no key', () => {
    expect(dashboardSchema.strict().safeParse(raw).success).toBe(true);
    // zod strips unknown keys on nested objects, so equality proves nothing was dropped.
    expect(dashboardSchema.parse(raw)).toEqual(raw);
  });
});

describe('FinanceDashboardView states (spec 4.2)', () => {
  it('shows the loading skeleton, not figures, before data arrives', () => {
    const html = view(null);
    expect(html).toContain('aria-busy="true"');
    expect(html).not.toContain(ar.finance.dashboard.kpi_title);
  });

  it('shows an inline error with Retry and keeps the header actions usable', () => {
    const html = view(null, 'The finance desk could not be reached.');
    expect(html).toContain('The finance desk could not be reached.');
    expect(html).toContain(ar.finance.dashboard.retry);
    expect(html).toContain('href="/finance/payments/new"');
    expect(html).toContain('href="/finance/flats"');
    expect(html).toContain('role="alert"');
  });

  it('renders the loaded body with the mockup copy', () => {
    const data = dashboardSchema.parse(raw);
    const html = view(data);
    expect(html).toContain(ar.finance.dashboard.kpi_title);
    expect(html).toContain(ar.finance.dashboard.top_title);
    expect(html).toContain(ar.finance.dashboard.close_title);
    expect(html).not.toContain('title_named');
  });

  it('renders the empty state when nothing has been billed and nobody owes', () => {
    const empty = dashboardSchema.parse({
      ...(raw as object),
      cohort: { charges: '0.00', allocated: '0.00', open: '0.00', rate: null },
      outstanding: '0.00',
      owingFlats: 0,
      byBuilding: [],
      topOwing: [],
      unapplied: { count: 0, total: '0.00', oldest: [] },
      aging: { current: '0.00', d31_60: '0.00', d61_90: '0.00', over90: '0.00' },
    });
    const html = view(empty);
    expect(html).toContain(ar.finance.dashboard.story_empty);
    expect(html).toContain(ar.finance.dashboard.no_overdue);
    expect(html).not.toContain('NaN');
  });
});
